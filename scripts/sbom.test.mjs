// Spec for scripts/sbom.mjs (DW-53 1/2): CycloneDX 1.5 SBOMs for the npm and
// Cargo dependency sets, read from the committed lockfiles. Pure layer
// (npmComponents / cargoComponents / bom) and the CLI boundary in a temp root.
// Run: node scripts/sbom.test.mjs
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SCRIPT = path.join(HERE, 'sbom.mjs');
const load = () => import(pathToFileURL(SCRIPT).href);

const LOCK = {
  name: 'personas',
  version: '9.9.9',
  lockfileVersion: 3,
  packages: {
    '': { name: 'personas', version: '9.9.9' },
    'node_modules/react': { version: '18.3.1' },
    'node_modules/vitest': { version: '2.0.0', dev: true },
    'node_modules/fsevents': { version: '2.3.3', optional: true },
    'node_modules/peerish': { version: '1.0.0', devOptional: true },
    'node_modules/@scope/pkg': { version: '1.0.0' },
    'node_modules/a/node_modules/b': { version: '0.1.0' },
    'node_modules/@scope/pkg/node_modules/@other/x': { version: '3.0.0' },
    'node_modules/linked': { resolved: 'packages/linked', link: true },
    'node_modules/noversion': {},
    'packages/linked': { version: '0.0.1' },
    'node_modules/dupe/node_modules/react': { version: '18.3.1' },
  },
};

const CARGO = `# This file is automatically @generated by Cargo.
version = 3

[[package]]
name = "serde"
version = "1.0.200"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "abc"

[[package]]
name = "personas"
version = "1.1.0"
dependencies = [
 "serde",
]

[[package]]
name = "gitdep"
version = "0.2.0"
source = "git+https://example.com/gitdep?rev=1#1"

[[package]]
name = "anyhow"
version = "1.0.86"
source = "registry+https://github.com/rust-lang/crates.io-index"
`;

const purls = (cs) => cs.map((c) => c.purl);

test('npm: dev excluded, optional/devOptional kept, root/link/no-version skipped', async () => {
  const { npmComponents } = await load();
  const p = purls(npmComponents(LOCK));
  assert.ok(p.includes('pkg:npm/react@18.3.1'));
  assert.ok(p.includes('pkg:npm/fsevents@2.3.3'));
  assert.ok(p.includes('pkg:npm/peerish@1.0.0'));
  assert.ok(!p.some((x) => x.includes('vitest')), 'dev: true is excluded');
  assert.ok(!p.some((x) => x.includes('linked')), 'link entries skipped');
  assert.ok(!p.some((x) => x.includes('noversion')), 'versionless entries skipped');
  assert.ok(!p.some((x) => x.includes('personas')), 'root is never a component');
});

test('npm: nested name is after the last node_modules/, scoped @ is %40', async () => {
  const { npmComponents } = await load();
  const cs = npmComponents(LOCK);
  const b = cs.find((c) => c.purl === 'pkg:npm/b@0.1.0');
  assert.ok(b, 'nested a/node_modules/b -> b');
  assert.equal(b.name, 'b');
  const s = cs.find((c) => c.purl === 'pkg:npm/%40scope/pkg@1.0.0');
  assert.ok(s, 'scoped purl encodes @');
  assert.equal(s.name, '@scope/pkg');
  assert.ok(purls(cs).includes('pkg:npm/%40other/x@3.0.0'));
});

test('npm: components unique by purl, sorted, bom-ref === purl, typed library', async () => {
  const { npmComponents } = await load();
  const cs = npmComponents(LOCK);
  const p = purls(cs);
  assert.equal(new Set(p).size, p.length, 'deduped');
  assert.deepEqual(p, [...p].sort(), 'sorted by purl');
  assert.equal(p.filter((x) => x === 'pkg:npm/react@18.3.1').length, 1);
  assert.equal(cs.length, 6);
  for (const c of cs) {
    assert.equal(c.type, 'library');
    assert.equal(c['bom-ref'], c.purl);
    assert.equal(typeof c.version, 'string');
  }
});

test('cargo: only packages with a source, purl pkg:cargo, sorted', async () => {
  const { cargoComponents } = await load();
  const cs = cargoComponents(CARGO);
  assert.deepEqual(purls(cs), [
    'pkg:cargo/anyhow@1.0.86',
    'pkg:cargo/gitdep@0.2.0',
    'pkg:cargo/serde@1.0.200',
  ]);
  const serde = cs.find((c) => c.name === 'serde');
  assert.equal(serde.version, '1.0.200');
  assert.equal(serde.type, 'library');
  assert.equal(serde['bom-ref'], serde.purl);
});

test('bom: CycloneDX 1.5 envelope', async () => {
  const { bom, cargoComponents } = await load();
  const comps = cargoComponents(CARGO);
  const b = bom(comps, { name: 'personas', version: '9.9.9' });
  assert.equal(b.bomFormat, 'CycloneDX');
  assert.equal(b.specVersion, '1.5');
  assert.match(b.serialNumber, /^urn:uuid:[0-9a-f-]{36}$/);
  assert.equal(b.version, 1);
  assert.deepEqual(b.metadata.component, { type: 'application', name: 'personas', version: '9.9.9' });
  assert.ok(!Number.isNaN(Date.parse(b.metadata.timestamp)));
  assert.equal(new Date(b.metadata.timestamp).toISOString(), b.metadata.timestamp);
  assert.deepEqual(b.components, comps);
});

const mkRoot = ({ cargo = true } = {}) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'sbom-spec-'));
  fs.writeFileSync(path.join(root, 'package.json'), JSON.stringify({ name: 'personas', version: '9.9.9' }));
  fs.writeFileSync(path.join(root, 'package-lock.json'), JSON.stringify(LOCK));
  if (cargo) {
    fs.mkdirSync(path.join(root, 'src-tauri'));
    fs.writeFileSync(path.join(root, 'src-tauri', 'Cargo.lock'), CARGO);
  }
  return root;
};
const run = (args) => spawnSync(process.execPath, [SCRIPT, ...args], { encoding: 'utf8' });

test('cli: writes both SBOMs and prints the counts', () => {
  assert.ok(fs.existsSync(SCRIPT), 'scripts/sbom.mjs exists');
  const root = mkRoot();
  const out = path.join(root, 'out');
  const r = run(['--root', root, '--out', out]);
  assert.equal(r.status, 0, r.stderr);
  const line = JSON.parse(r.stdout.trim().split('\n').pop());
  assert.equal(line.npm, 6);
  assert.equal(line.cargo, 3);
  assert.equal(line.files.length, 2);
  const npmFile = path.join(out, 'personas-9.9.9.npm.cdx.json');
  const cargoFile = path.join(out, 'personas-9.9.9.cargo.cdx.json');
  for (const f of [npmFile, cargoFile]) assert.ok(fs.existsSync(f), `${f} written`);
  const npm = JSON.parse(fs.readFileSync(npmFile, 'utf8'));
  const cargo = JSON.parse(fs.readFileSync(cargoFile, 'utf8'));
  assert.equal(npm.bomFormat, 'CycloneDX');
  assert.equal(npm.metadata.component.version, '9.9.9');
  assert.equal(npm.components.length, 6);
  assert.deepEqual(purls(cargo.components), ['pkg:cargo/anyhow@1.0.86', 'pkg:cargo/gitdep@0.2.0', 'pkg:cargo/serde@1.0.200']);
});

test('cli: --version overrides package.json and defaults --out to <root>/dist/sbom', () => {
  assert.ok(fs.existsSync(SCRIPT), 'scripts/sbom.mjs exists');
  const root = mkRoot();
  const r = run(['--root', root, '--version', '2.0.0-rc.1']);
  assert.equal(r.status, 0, r.stderr);
  assert.ok(fs.existsSync(path.join(root, 'dist', 'sbom', 'personas-2.0.0-rc.1.npm.cdx.json')));
  assert.ok(fs.existsSync(path.join(root, 'dist', 'sbom', 'personas-2.0.0-rc.1.cargo.cdx.json')));
});

test('cli: a missing Cargo.lock exits 2 and writes nothing', () => {
  assert.ok(fs.existsSync(SCRIPT), 'scripts/sbom.mjs exists');
  const root = mkRoot({ cargo: false });
  const out = path.join(root, 'out');
  const r = run(['--root', root, '--out', out]);
  assert.equal(r.status, 2);
  assert.ok(r.stderr.trim().length > 0, 'explains on stderr');
  assert.ok(!fs.existsSync(out) || fs.readdirSync(out).length === 0, 'no files written');
});

test('cli: an unknown flag exits 2', () => {
  assert.ok(fs.existsSync(SCRIPT), 'scripts/sbom.mjs exists');
  const root = mkRoot();
  const r = run(['--root', root, '--bogus']);
  assert.equal(r.status, 2);
  assert.ok(r.stderr.trim().length > 0);
  assert.ok(!fs.existsSync(path.join(root, 'dist')), 'no files written');
});
