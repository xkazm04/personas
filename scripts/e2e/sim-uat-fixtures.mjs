#!/usr/bin/env node
// Grand Simulation -> /uat fixtures (gap G10, direction 1; see
// docs/architecture/grand-simulation/uat-scenario.md).
//
// Reads the live Personas database and prints the FIXTURES section of a /uat env.md for one
// workspace: projects and their App Masters, the Architect, goals, KPIs with their last
// measurement, the idea backlog by status, and the active-persona headroom. Every line names
// its source row and updated_at so a later run can tell simulation residue from product data.
//
//   node scripts/e2e/sim-uat-fixtures.mjs --workspace Bank
//   node scripts/e2e/sim-uat-fixtures.mjs --workspace Bank --out uat/env.sim.md
//
// Read-only. Never writes into a bank repository; the App Master copies the section.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';

const args = process.argv.slice(2);
const opt = (n, d) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : d; };
const WORKSPACE = opt('--workspace', '');
const OUT = opt('--out', '');
const DB_PATH = process.env.PERSONAS_DB || path.join(process.env.APPDATA || os.homedir(), 'com.personas.desktop', 'personas.db');
if (!WORKSPACE) { console.error('usage: --workspace <id | name> [--out file]'); process.exit(1); }

const db = new DatabaseSync(DB_PATH, { readOnly: true });
const columns = (t) => db.prepare(`pragma table_info(${t})`).all().map((c) => c.name);
const ws = db.prepare('select * from dev_workspaces where id = ? or name = ?').get(WORKSPACE, WORKSPACE);
if (!ws) { console.error(`no workspace "${WORKSPACE}"`); process.exit(1); }
// The never-delete tag arrives with migration e24; a database the app has not migrated yet has no column.
const protectedTag = columns('dev_workspaces').includes('last_working_version') ? Boolean(ws.last_working_version) : null;

const projects = db.prepare('select id, name, root_path, status, tech_stack, updated_at from dev_projects where workspace_id = ? order by name').all(ws.id);
const personas = db.prepare("select id, name, enabled, lifecycle, design_context, updated_at from personas where design_context like '%devProjectId%' or design_context like '%workspaceId%'").all();
const pin = (p) => { try { return JSON.parse(p.design_context || '{}'); } catch { return {}; } };
const appMasterOf = (projectId) => personas.find((p) => pin(p).devProjectId === projectId);
const architect = personas.find((p) => pin(p).workspaceId === ws.id);
const charters = db.prepare('select persona_id, title, status, cadence, updated_at from persona_responsibilities').all()
  .map((c) => { let cad = {}; try { cad = JSON.parse(c.cadence || '{}'); } catch { /* unreadable cadence reads as attention off */ } return { ...c, attention_enabled: Boolean(cad.attentionEnabled ?? cad.attention_enabled) }; });
const chartersOf = (personaId) => charters.filter((c) => c.persona_id === personaId && c.status === 'active');

const enabledCount = db.prepare("select count(*) as n from personas where enabled = 1 and (lifecycle is null or lifecycle = 'active')").get().n;
const capRow = db.prepare("select value from app_settings where key = 'max_active_personas'").get?.();
const cap = Number(capRow?.value ?? 10);

const box = (ok) => (ok ? '- [x]' : '- [ ]');
const src = (table, id, updated) => `(${table} ${String(id).slice(0, 8)}, updated ${updated ?? 'n/a'})`;
const lines = [];
lines.push(`## FIXTURES — generated from the simulation (workspace ${ws.name}, ${new Date().toISOString()})`);
lines.push('');
lines.push(`Generated by scripts/e2e/sim-uat-fixtures.mjs from ${DB_PATH}. Do not hand-edit; regenerate.`);
lines.push('');
lines.push(`${box(true)} Workspace **${ws.name}** ${src('dev_workspaces', ws.id, ws.updated_at)}${protectedTag === null ? ' (protection column not migrated yet)' : protectedTag ? ' (protected: last working version)' : ' (NOT protected)'}`);
lines.push(`${box(Boolean(architect))} Architect ${architect ? `**${architect.name}** ${architect.enabled ? 'enabled' : 'disabled'}, ${chartersOf(architect.id).length} active charter(s) ${src('personas', architect.id, architect.updated_at)}` : 'none adopted yet (journey architect-notices-an-unowned-project needs one)'}`);
lines.push(`${box(enabledCount < cap)} Active-persona headroom: ${enabledCount} of ${cap} (${cap - enabledCount} free)`);
lines.push('');
lines.push('### Projects');
for (const p of projects) {
  const am = appMasterOf(p.id);
  const repo = fs.existsSync(path.join(p.root_path, '.git'));
  lines.push(`${box(repo)} **${p.name}** at ${p.root_path} ${repo ? 'git repository' : 'NO git repository'} ${src('dev_projects', p.id, p.updated_at)}`);
  lines.push(`  ${box(Boolean(am))} App Master ${am ? `**${am.name}** ${am.enabled ? 'enabled' : 'disabled'}, ${chartersOf(am.id).length} active charter(s), attention ${chartersOf(am.id).some((c) => c.attention_enabled) ? 'on' : 'OFF'} ${src('personas', am.id, am.updated_at)}` : 'none (an unowned project is a fixture for the Architect journey)'}`);
  const goals = db.prepare('select id, title, status, progress, updated_at from dev_goals where project_id = ? order by order_index').all(p.id);
  lines.push(`  ${box(goals.length > 0)} Goals: ${goals.length}${goals.map((g) => `\n    - ${g.title} — ${g.status} ${g.progress ?? 0}% ${src('dev_goals', g.id, g.updated_at)}`).join('')}`);
  const kpis = db.prepare('select id, name, status, current_value, unit, last_measured_at, updated_at from dev_kpis where project_id = ? order by name').all(p.id);
  const measured = kpis.filter((k) => k.last_measured_at);
  lines.push(`  ${box(kpis.length > 0)} KPIs: ${kpis.length} (${measured.length} measured)${kpis.slice(0, 12).map((k) => `\n    - ${k.name} — ${k.status}${k.current_value != null ? ` ${k.current_value}${k.unit ? ' ' + k.unit : ''}` : ''}${k.last_measured_at ? ` measured ${k.last_measured_at}` : ' never measured'} ${src('dev_kpis', k.id, k.updated_at)}`).join('')}${kpis.length > 12 ? `\n    - … ${kpis.length - 12} more` : ''}`);
  const ideas = db.prepare('select status, count(*) as n from dev_ideas where project_id = ? group by status').all(p.id);
  lines.push(`  ${box(ideas.length > 0)} Ideas: ${ideas.length ? ideas.map((i) => `${i.status} ${i.n}`).join(', ') : 'none'}`);
}
lines.push('');
lines.push('### Still needed by the bank journeys (fill in per run)');
lines.push('- [ ] A retail account fixture with an IBAN and one completed payment (journeys open-account, pay-a-friend)');
lines.push('- [ ] A 300-line payment batch file (journey batch-payroll)');
lines.push('- [ ] A signed contract pair with a stored hash (journey exchange-a-contract)');
lines.push('- [ ] A loan application in the officer queue (journey apply-for-a-loan)');
lines.push('- [ ] One fund with a fee schedule (journey invest-in-a-fund)');
lines.push('- [ ] scenario.json with the load envelope (journey month-end-under-load)');
db.close();

const text = lines.join('\n') + '\n';
if (OUT) { fs.writeFileSync(OUT, text); console.log(`wrote ${OUT} (${lines.length} lines)`); } else { process.stdout.write(text); }
