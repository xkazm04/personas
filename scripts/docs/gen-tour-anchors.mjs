#!/usr/bin/env node
/**
 * Build-time tour-anchor manifest for Generative Tours.
 *
 * Scans the React source tree for the stable spotlight anchors a guided tour
 * may target (`data-testid` literals + dynamic template prefixes), plus the
 * navigation vocabulary the tour driver (`GuidedTour.tsx`) understands
 * (sidebar sections from `SidebarSection`, sub-tab setter names from the
 * driver itself). Emits TWO lock-step artifacts:
 *
 *   1. src/features/onboarding/anchors/tourAnchorManifest.json
 *      — imported by `dynamicTours.ts` to validate Athena-composed tours on
 *        ingest (frontend defense-in-depth).
 *   2. src-tauri/src/companion/generated_tour_anchors.rs
 *      — the Rust allow-list `companion::tours` validates `compose_tour`
 *        output against BEFORE a generated tour is ever persisted.
 *
 * Extraction mirrors the proven anchor-drift gate in
 * `src/stores/slices/system/__tests__/tourAnchors.test.ts`:
 *   - VERBATIM testids: `data-testid="x"`, `data-testid={'x'}`,
 *     `data-testid={`x`}` (no interpolation), `testId="x"`, `testId: 'x'`.
 *   - DYNAMIC template prefixes: `data-testid={`prefix-${…}`}` — a composed
 *     anchor is accepted when it starts with a known prefix (the runtime
 *     `highlightMissing` degradation covers a suffix that never renders).
 *
 * Output is deterministic (sorted, no timestamps) so re-runs diff cleanly.
 *
 * Usage: node scripts/docs/gen-tour-anchors.mjs
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..", "..");
const SRC = resolve(ROOT, "src");
const JSON_OUT = resolve(ROOT, "src/features/onboarding/anchors/tourAnchorManifest.json");
const RUST_OUT = resolve(ROOT, "src-tauri/src/companion/generated_tour_anchors.rs");
const TYPES_FILE = resolve(ROOT, "src/lib/types/types.ts");
const DRIVER_FILE = resolve(ROOT, "src/features/onboarding/components/GuidedTour.tsx");

// -- corpus ---------------------------------------------------------------

function collectSourceFiles(dir, acc) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      collectSourceFiles(full, acc);
    } else if (
      /\.(ts|tsx)$/.test(entry.name) &&
      !/\.(test|spec)\.(ts|tsx)$/.test(entry.name) &&
      entry.name !== "tourSlice.ts"
    ) {
      acc.push(full);
    }
  }
  return acc;
}

const corpus = collectSourceFiles(SRC, [])
  .map((f) => readFileSync(f, "utf8"))
  .join("\n");

// -- testids --------------------------------------------------------------

const TESTID_RES = [
  /data-testid="([A-Za-z0-9_-]+)"/g,
  /data-testid=\{'([A-Za-z0-9_-]+)'\}/g,
  /data-testid=\{"([A-Za-z0-9_-]+)"\}/g,
  /data-testid=\{`([A-Za-z0-9_-]+)`\}/g,
  /testId="([A-Za-z0-9_-]+)"/g,
  /testId:\s*['"]([A-Za-z0-9_-]+)['"]/g,
];

const testids = new Set();
for (const re of TESTID_RES) {
  for (const m of corpus.matchAll(re)) testids.add(m[1]);
}

// Dynamic template prefixes, e.g. data-testid={`design-subtab-${tab.id}`}
const dynamicPrefixes = new Set();
for (const m of corpus.matchAll(/data-testid=\{`([A-Za-z0-9_-]+-)\$\{/g)) {
  dynamicPrefixes.add(m[1]);
}

// -- nav vocabulary -------------------------------------------------------

// SidebarSection union from src/lib/types/types.ts
const typesSrc = readFileSync(TYPES_FILE, "utf8");
const sidebarMatch = typesSrc.match(/export type SidebarSection\s*=\s*([^;]+);/);
if (!sidebarMatch) {
  console.error("Could not find `export type SidebarSection` in src/lib/types/types.ts");
  process.exit(1);
}
const sidebarSections = [...sidebarMatch[1].matchAll(/"([a-z0-9-]+)"/g)].map((m) => m[1]);

// Sub-tab setters the driver actually dispatches (data-driven from GuidedTour.tsx)
const driverSrc = readFileSync(DRIVER_FILE, "utf8");
const subTabSetters = [
  ...new Set([...driverSrc.matchAll(/nav\.subTabSetter\s*===\s*'(\w+)'/g)].map((m) => m[1])),
];

// -- sanity ---------------------------------------------------------------

if (testids.size < 20) {
  console.error(`Parsed only ${testids.size} testids — refusing to write a suspiciously thin manifest`);
  process.exit(1);
}
if (sidebarSections.length === 0 || subTabSetters.length === 0) {
  console.error("Empty sidebarSections or subTabSetters — refusing to write");
  process.exit(1);
}

const manifest = {
  $comment:
    "AUTO-GENERATED by scripts/docs/gen-tour-anchors.mjs — DO NOT EDIT. Re-run: node scripts/docs/gen-tour-anchors.mjs",
  testids: [...testids].sort(),
  dynamicPrefixes: [...dynamicPrefixes].sort(),
  sidebarSections: [...sidebarSections].sort(),
  subTabSetters: [...subTabSetters].sort(),
};

mkdirSync(dirname(JSON_OUT), { recursive: true });
writeFileSync(JSON_OUT, JSON.stringify(manifest, null, 2) + "\n");

const rustList = (name, doc, items) =>
  `/// ${doc}\npub const ${name}: &[&str] = &[\n${items.map((k) => `    "${k}",`).join("\n")}\n];\n`;

const rust = `// AUTO-GENERATED by scripts/docs/gen-tour-anchors.mjs — DO NOT EDIT
// Re-run: node scripts/docs/gen-tour-anchors.mjs
//
// Tour-anchor allow-lists for \`compose_tour\` (Generative Tours). The JSON
// twin (src/features/onboarding/anchors/tourAnchorManifest.json) is used by
// the frontend; both are generated from the same scan so they never drift.

${rustList("TOUR_TESTIDS", `Every statically-declared \`data-testid\` in src/ (${manifest.testids.length}).`, manifest.testids)}
${rustList("TOUR_TESTID_DYNAMIC_PREFIXES", "Dynamic template prefixes — an anchor starting with one of these is accepted.", manifest.dynamicPrefixes)}
${rustList("TOUR_SIDEBAR_SECTIONS", "Valid \`nav.sidebarSection\` values (SidebarSection union).", manifest.sidebarSections)}
${rustList("TOUR_SUBTAB_SETTERS", "Sub-tab setter names GuidedTour.tsx dispatches.", manifest.subTabSetters)}`;

writeFileSync(RUST_OUT, rust);

console.log(
  `tour-anchor manifest: ${manifest.testids.length} testids, ${manifest.dynamicPrefixes.length} dynamic prefixes, ` +
    `${manifest.sidebarSections.length} sections, ${manifest.subTabSetters.length} setters\n → ${JSON_OUT}\n → ${RUST_OUT}`,
);
