#!/usr/bin/env node
// PreToolUse guard: refuse a WHOLE-file Read of a large GENERATED artifact.
//
// WHY THIS EXISTS (2026-09-08). Replaying 30 days of this machine's Claude Code
// transcripts (5,945 sessions, instrument: ai-registry
// scripts/measure-large-reads.mjs) found 208 whole reads of text files over
// 350 lines. In this repo the biggest were not source: `.claude/active-runs.md`
// read whole five times at ~3,950 lines, `.claude/codebase-context.md` twice at
// ~7,600, and a dozen `tool-results/*.txt` overflow files — the spill the
// harness makes when a tool's output was already too large to show, then read
// back whole. Source files over the threshold (a 2,800-line Rust module, a
// 2,900-line pipeline) are the working set and must stay readable.
//
// So this guard sorts by the CLASS of the file, not its size alone. Size is
// only the gate inside a class (registry: prompt-assembly /
// elision-to-a-refetch-pointer — "class by what produced the output; size acts
// only inside a class"). Two classes are blocked when read whole above the
// threshold; everything else is allowed without comment:
//
//   harness-overflow    path contains a `tool-results` segment
//   generated-artifact  one of the first 8 lines declares a generator or a
//                       ledger ("Generated:", "auto-generated", "Ledger")
//
// A targeted read (offset or limit set) always passes — the agent already knows
// what it needs. A missing file passes — let Read report it.
//
// FAIL-OPEN, LOUDLY, like guard-concurrent-cargo: an empty or unparseable
// payload means the read was NOT inspected, and that is said on stderr rather
// than swallowed. Override for one deliberate whole read: WHOLE_READ_GUARD=off.
// Threshold: WHOLE_READ_MIN_LINES (default 350).
import fs from 'node:fs';

const MIN_LINES = (() => {
  const n = Number(process.env.WHOLE_READ_MIN_LINES);
  return Number.isInteger(n) && n > 0 ? n : 350;
})();
const GENERATED = /^\s*(?:>\s*)?(?:#.*)?(?:auto-?generated|generated:|generated by|\bledger\b)/i;

/** Pure decision function — exported for the test and for replay. */
export function decide(input, readFile = fs.readFileSync, exists = fs.existsSync) {
  const fp = String(input?.file_path ?? '');
  if (!fp) return { decision: 'allow', reason: 'no path' };
  if (input.offset != null || input.limit != null) return { decision: 'allow', reason: 'targeted read' };
  if (!exists(fp)) return { decision: 'allow', reason: 'missing file' };
  let body;
  try { body = readFile(fp, 'utf8'); } catch { return { decision: 'allow', reason: 'unreadable' }; }
  const lines = body.split('\n');
  if (lines.length <= MIN_LINES) return { decision: 'allow', reason: 'under threshold', lines: lines.length };
  let cls = 'source';
  if (/[\\/]tool-results[\\/]/.test(fp)) cls = 'harness-overflow';
  else if (lines.slice(0, 8).some((l) => GENERATED.test(l))) cls = 'generated-artifact';
  if (cls === 'source') return { decision: 'allow', reason: 'source file', lines: lines.length, class: cls };
  return { decision: 'block', reason: `${lines.length} lines of ${cls}`, lines: lines.length, class: cls };
}

const isMain = process.argv[1] && import.meta.url === new URL(`file:///${process.argv[1].replace(/\\/g, '/')}`).href;
if (isMain) {
  let payload = '';
  process.stdin.setEncoding('utf8');
  for await (const chunk of process.stdin) payload += chunk;

  if (!payload.trim()) {
    console.error('[whole-read-guard] DEGRADED: no hook payload on stdin — the read was not inspected.');
    process.exit(0);
  }
  let input;
  try { input = JSON.parse(payload)?.tool_input ?? {}; } catch (err) {
    console.error(`[whole-read-guard] DEGRADED: unparseable hook payload (${err?.message ?? err}).`);
    process.exit(0);
  }
  if (process.env.WHOLE_READ_GUARD === 'off') process.exit(0);

  const verdict = decide(input);
  if (verdict.decision !== 'block') process.exit(0);

  console.error(
    `[whole-read-guard] BLOCKED — ${input.file_path} is ${verdict.lines} lines of ${verdict.class}.\n` +
      `A generated artifact or a harness overflow file read whole re-ingests what a generator\n` +
      `already summarized, at ~${Math.round(verdict.lines * 12)} tokens. Instead:\n` +
      `  - read the part you need:   Read with offset/limit\n` +
      `  - search it:                Grep for the term you are after\n` +
      `  - delegate it:              an Explore subagent reads it and returns the answer\n` +
      `  - override once:            WHOLE_READ_GUARD=off (threshold: WHOLE_READ_MIN_LINES=${MIN_LINES})`,
  );
  process.exit(2); // exit 2 = block the tool call and show stderr to the agent
}
